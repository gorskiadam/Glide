import { createHash } from 'node:crypto'
import { readdirSync } from 'node:fs'
import { defineConfig } from 'vitest/config'
import type { Plugin } from 'vite'
import react from '@vitejs/plugin-react'
import tailwindcss from '@tailwindcss/vite'

/**
 * Writes `sw.js` at build time: a small service worker that stores the whole app
 * on the first visit, so that Glide starts and works without a connection.
 * Fonts for scripts the app does not use (Cyrillic, Greek, Vietnamese) are left
 * out of the first download and stored only if the browser ever asks for them.
 */
function offline(): Plugin {
  return {
    name: 'glide-offline',
    apply: 'build',
    generateBundle(_options, bundle) {
      const built = Object.keys(bundle).filter((file) => !file.endsWith('.map') && !(file.endsWith('.woff2') && !/-latin(-ext)?-/.test(file)) && !file.endsWith('.woff'))
      const files = ['./', ...built.filter((f) => f !== 'index.html'), ...readdirSync('public')].map((f) => (f === './' ? f : `./${f}`))
      const index = bundle['index.html']
      const version = createHash('sha256')
        // The worker's own code is part of the version, so a change to it also refreshes the stored files.
        .update(files.join('|') + (index && 'source' in index ? String(index.source) : '') + serviceWorker('', files))
        .digest('hex')
        .slice(0, 12)
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: serviceWorker(version, files) })
    },
  }
}

function serviceWorker(version: string, files: string[]): string {
  return `// Generated by vite.config.ts. Do not edit.
const CACHE = 'glide-${version}'
const FILES = ${JSON.stringify(files)}

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith('glide-') && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return
  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      // Every page of the app is the same file: routes live in the URL hash.
      // ignoreVary: some servers send "Vary: Origin", which would make stored files miss.
      const cached = await cache.match(request.mode === 'navigate' ? './' : request, { ignoreSearch: true, ignoreVary: true })
      if (cached) return cached
      const response = await fetch(request)
      if (response.ok && response.type === 'basic') cache.put(request, response.clone())
      return response
    }),
  )
})
`
}

export default defineConfig({
  plugins: [react(), tailwindcss(), offline()],
  server: { port: 5183, strictPort: true },
  preview: { port: 5184, strictPort: true },
  test: { environment: 'node', include: ['src/**/*.test.ts'] },
})
